const KEYWORDS = [...TABLE].sort((a, b) => b[0].length - a[0].length);

/** 공백·중점 등을 지워 '반팔 티셔츠', '데님 팬츠' 같은 띄어쓰기 변형을 흡수한다 */
function squash(s: string): string {
  return s.replace(/[\s·・_\-/]/g, '').toLowerCase();
}

/**
 * 상품명에서 옷장 분류를 추정한다. 못 알아보면 null.
 * null 은 "옷이 아니다"가 아니라 **"모르겠다"** 라는 뜻이다 — 호출부에서 지우지 말 것.
 */
export function classifyProduct(name: string): ProductGuess | null {
  if (!name) return null;
  const hay = squash(name);
  for (const [word, large, small] of KEYWORDS) {
    if (hay.includes(squash(word))) return { large, small, matched: word };
  }
  return null;
}
